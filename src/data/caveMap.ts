/**
 * Tile type constants for the cave map.
 * 0 = Walkable cave floor
 * 1 = Solid rock wall
 * 2 = Cave entrance floor (walkable)
 */
export enum TileType {
  FLOOR = 0,
  WALL = 1,
  ENTRANCE = 2,
}

export interface TileCoord {
  col: number;
  row: number;
}

